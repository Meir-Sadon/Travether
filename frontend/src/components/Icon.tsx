export type IconName = keyof typeof paths

const directional = new Set<IconName>(['back', 'forward', 'send'])

type IconProps = Omit<SVGProps<SVGSVGElement>, 'name'> & {
  name: IconName
  size?: number
  /** Accessible name. Without it the icon is decorative and hidden from screen readers. */
  label?: string
}

export function Icon({ name, size = 20, label, className, ...rest }: IconProps) {
  const classes = ['icon', directional.has(name) && 'icon--directional', className].filter(Boolean).join(' ')
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={classes}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      {...rest}
    >
      {paths[name]}
    </svg>
  )
}
